type Widen<T> = {
  [K in keyof T]: T[K] extends (...args: infer A) => infer R ? (...args: A) => R
    : T[K] extends readonly unknown[] ? readonly string[]
    : string
}

export type EmailT = Widen<typeof strings['de']>

export function getT(locale?: string | null): EmailT {
  return strings[getEmailLocale(locale)]
}
