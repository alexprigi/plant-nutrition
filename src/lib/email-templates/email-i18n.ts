export type EmailLocale = 'it' | 'de' | 'en'

export function getEmailLocale(locale?: string | null): EmailLocale {
  if (locale === 'it' || locale === 'de' || locale === 'en') return locale
  return 'de'
}

export function formatEmailDate(dateStr: string, locale: EmailLocale): string {
  const lngMap = { it: 'it-IT', de: 'de-DE', en: 'en-GB' } as const
  return new Date(dateStr).toLocaleDateString(lngMap[locale], {
    weekday: 'long', day: 'numeric', month: 'long', year: 'numeric',
  })
}

